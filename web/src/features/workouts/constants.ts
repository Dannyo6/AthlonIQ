export function createBlankSet(
  exerciseName: string,
  order: number,
  isBodyweight: boolean
): ExerciseSet {
  return {
    id: `set-${Date.now()}-${order}`,
    exerciseName,
    setOrder: order,
    reps: 0,
    loadKg: 0,
    isBodyweight,
    rpe: null,
    rir: null,
    isCompleted: false,
    isPr: false,
  };
}

